"""Generate docs/ctl017.eds and the object table in
docs/ctl017_object_dictionary.md from the firmware object dictionary.

The firmware table (firmware/ctl017/app/src/ctl017_od.c) is the source.
ctl017_od_dump prints it; this script renders it. With --check it fails
if the committed files differ from what it would write.

Usage:
  gen_od_docs.py --dump build/tools/ctl017_od/ctl017_od_dump --docs docs [--check]
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN GENERATED OD TABLE (tools/ctl017_od/gen_od_docs.py) -->"
END = "<!-- END GENERATED OD TABLE -->"

TYPES = {1: ("BOOLEAN", 1), 2: ("INTEGER8", 1), 3: ("INTEGER16", 2), 4: ("INTEGER32", 4),
         5: ("UNSIGNED8", 1), 6: ("UNSIGNED16", 2), 7: ("UNSIGNED32", 4)}

# Object (parent) names for records and arrays.
OBJECT_NAMES = {
    0x1003: ("Pre-defined error field", 0x8),
    0x1016: ("Consumer heartbeat time", 0x8),
    0x1018: ("Identity object", 0x9),
    0x1400: ("RPDO1 communication parameter", 0x9),
    0x1401: ("RPDO2 communication parameter", 0x9),
    0x1600: ("RPDO1 mapping parameter", 0x9),
    0x1601: ("RPDO2 mapping parameter", 0x9),
    0x1800: ("TPDO1 communication parameter", 0x9),
    0x1801: ("TPDO2 communication parameter", 0x9),
    0x1A00: ("TPDO1 mapping parameter", 0x9),
    0x1A01: ("TPDO2 mapping parameter", 0x9),
    0x2000: ("LiftStatus", 0x9),
    0x2001: ("LiftStatus2", 0x9),
    0x2010: ("LiftCommand", 0x9),
    0x2011: ("AuxCommand", 0x9),
    0x2100: ("Stop positions", 0x8),
    0x2101: ("Lift parameters", 0x9),
    0x2300: ("Diagnostics", 0x9),
}
MANDATORY = [0x1000, 0x1001, 0x1018]
EDS_ACCESS = {"const": "const", "ro": "ro", "rw": "rw", "rww": "rww", "rw_preop": "rw"}
MD_ACCESS = {"const": "const", "ro": "ro", "rw": "rw", "rww": "rww (RPDO only)",
             "rw_preop": "rw (PRE-OP only)"}


def load(dump_exe):
    out = subprocess.run([dump_exe], check=True, capture_output=True, text=True).stdout
    return [json.loads(line) for line in out.splitlines() if line.strip()]


def fmt_value(e):
    name, size = TYPES[e["type"]]
    v = e["value"]
    if name.startswith("UNSIGNED") and size >= 2:
        return "0x%0*X" % (size * 2, v)
    return str(v)


def group(entries):
    objs = {}
    for e in entries:
        objs.setdefault(e["index"], []).append(e)
    return dict(sorted(objs.items()))


def render_eds(entries):
    objs = group(entries)
    lines = []
    add = lines.append
    add("; CTL-017 upper-body controller, CANopen EDS draft (CiA 306 format).")
    add("; Generated by tools/ctl017_od/gen_od_docs.py from the firmware object")
    add("; dictionary. Do not edit by hand. Node-ID 0x10 is fixed in the values.")
    add("; Proposal for the owner, not a released device description.")
    add("")
    add("[FileInfo]")
    add("FileName=ctl017.eds")
    add("FileVersion=1")
    add("FileRevision=0")
    add("EDSVersion=4.0")
    add("Description=CTL-017 lift and upper-body I/O node, CAN3 node 0x10")
    add("CreatedBy=OpenAMRobot")
    add("")
    add("[DeviceInfo]")
    add("VendorName=OpenAMRobot")
    ident = {e["sub"]: e["value"] for e in objs[0x1018]}
    add("VendorNumber=0x%08X" % ident[1])
    add("ProductName=CTL-017")
    add("ProductNumber=0x%08X" % ident[2])
    add("RevisionNumber=0x%08X" % ident[3])
    for rate in (10, 20, 50, 125, 250, 500, 800, 1000):
        add("BaudRate_%d=%d" % (rate, 1 if rate == 500 else 0))
    add("SimpleBootUpMaster=0")
    add("SimpleBootUpSlave=1")
    add("Granularity=0")
    add("DynamicChannelsSupported=0")
    add("GroupMessaging=0")
    add("NrOfRXPDO=2")
    add("NrOfTXPDO=2")
    add("LSS_Supported=0")
    add("")
    add("[DummyUsage]")
    for d in range(1, 8):
        add("Dummy%04X=0" % d)
    add("")
    mand = [i for i in objs if i in MANDATORY]
    opt = [i for i in objs if i not in MANDATORY and i < 0x2000]
    manu = [i for i in objs if i >= 0x2000]
    for title, lst in (("MandatoryObjects", mand), ("OptionalObjects", opt), ("ManufacturerObjects", manu)):
        add("[%s]" % title)
        add("SupportedObjects=%d" % len(lst))
        for n, i in enumerate(lst, 1):
            add("%d=0x%04X" % (n, i))
        add("")
    for idx, subs in objs.items():
        is_var = len(subs) == 1 and subs[0]["sub"] == 0 and idx not in OBJECT_NAMES
        if is_var:
            e = subs[0]
            add("[%04X]" % idx)
            add("ParameterName=%s" % e["name"])
            add("ObjectType=0x7")
            add("DataType=0x%04X" % e["type"])
            add("AccessType=%s" % EDS_ACCESS[e["access"]])
            add("DefaultValue=%s" % fmt_value(e))
            add("PDOMapping=%d" % (1 if e["pdo"] else 0))
            add("")
            continue
        name, otype = OBJECT_NAMES[idx]
        add("[%04X]" % idx)
        add("ParameterName=%s" % name)
        add("ObjectType=0x%X" % otype)
        add("SubNumber=%d" % len(subs))
        add("")
        for e in subs:
            add("[%04Xsub%X]" % (idx, e["sub"]))
            add("ParameterName=%s" % e["name"])
            add("ObjectType=0x7")
            add("DataType=0x%04X" % e["type"])
            add("AccessType=%s" % EDS_ACCESS[e["access"]])
            add("DefaultValue=%s" % fmt_value(e))
            add("PDOMapping=%d" % (1 if e["pdo"] else 0))
            add("")
    return "\n".join(lines)


def render_md_table(entries):
    rows = [BEGIN, "",
            "| Index | Sub | Name | Type | Access | PDO | Default |",
            "|---|---|---|---|---|---|---|"]
    for e in sorted(entries, key=lambda x: (x["index"], x["sub"])):
        rows.append("| 0x%04X | %d | %s | %s | %s | %s | %s |" % (
            e["index"], e["sub"], e["name"].replace("|", "/"), TYPES[e["type"]][0],
            MD_ACCESS[e["access"]], "yes" if e["pdo"] else "", fmt_value(e)))
    rows += ["", END]
    return "\n".join(rows)


def splice(md_text, table):
    if BEGIN not in md_text or END not in md_text:
        raise SystemExit("markers not found in the object dictionary document")
    head, rest = md_text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + table + tail


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", required=True)
    ap.add_argument("--docs", required=True)
    ap.add_argument("--check", action="store_true")
    o = ap.parse_args()
    entries = load(o.dump)
    docs = Path(o.docs)
    eds_path = docs / "ctl017.eds"
    md_path = docs / "ctl017_object_dictionary.md"
    eds = render_eds(entries)
    md = splice(md_path.read_text(encoding="utf-8"), render_md_table(entries))
    if o.check:
        bad = []
        if not eds_path.exists() or eds_path.read_text(encoding="utf-8") != eds:
            bad.append(str(eds_path))
        if md_path.read_text(encoding="utf-8") != md:
            bad.append(str(md_path))
        if bad:
            print("out of date (run gen_od_docs.py without --check): " + ", ".join(bad))
            return 1
        print("object dictionary documents match the firmware (%d entries)" % len(entries))
        return 0
    eds_path.write_text(eds, encoding="utf-8")
    md_path.write_text(md, encoding="utf-8")
    print("wrote %s and %s" % (eds_path, md_path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
